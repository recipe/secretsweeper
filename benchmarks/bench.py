"""Benchmarks secretsweeper against Python regex and several Aho-Corasick libraries.

Masks the corpus generated by `gen_corpus.py` (a ~100 MiB file containing 10-20
rare, real-looking secrets and 3-4 fake PEM/SSH-key blocks). Each engine is
measured over several interleaved rounds (alternating engine order each round,
so system noise like thermal throttling or scheduler jitter doesn't
systematically favor whichever engine happens to run first or last) - a single
total wall-clock call per round, no internal averaging within a round, matching
how each library is actually used once on a file.

None of the comparison libraries implement masking/replacement themselves -
they only find match spans - so each gets the same handwritten, allocation-light
pure-Python reconstruction step (merge overlapping spans, cap each at
MAX_NUMBER_OF_STARS), and that reconstruction time is counted as part of its
total. secretsweeper's Zig core fuses search+replace natively, so its total is
just the one `secretsweeper.mask()` call.

Usage: run `gen_corpus.py` first (or pass --generate here), then:
    uv run --group benchmark python benchmarks/bench.py [--rounds N]
Writes benchmarks/data/results.json, consumed by `report.py`.
"""

import argparse
import importlib.metadata
import json
import pathlib
import pickle
import sys
import time

REPO_ROOT = pathlib.Path(__file__).parent.parent
sys.path.insert(0, str(REPO_ROOT))

DATA_DIR = pathlib.Path(__file__).parent / "data"
LIMIT = 15  # secretsweeper.MAX_NUMBER_OF_STARS


def _lib_version(dist_name: str) -> str | None:
    try:
        return importlib.metadata.version(dist_name)
    except importlib.metadata.PackageNotFoundError:
        return None


def apply_spans(text: bytes, spans: list[tuple[int, int]], limit: int = LIMIT) -> bytes:
    """
    Shared reconstruction: merge overlapping spans, replace each with min(length, limit) stars.

    Mirrors secretsweeper's own semantics. Written to minimize Python-level overhead:
    single sort, single pass, list+join instead of repeated bytearray growth.
    """
    if not spans:
        return bytes(text)
    spans.sort()
    merged = []
    cur_s, cur_e = spans[0]
    for s, e in spans[1:]:
        if s < cur_e:
            if e > cur_e:
                cur_e = e
        else:
            merged.append((cur_s, cur_e))
            cur_s, cur_e = s, e
    merged.append((cur_s, cur_e))

    parts = []
    append = parts.append
    pos = 0
    star = b"*"
    stars_cache = {n: star * n for n in range(limit + 1)}
    for s, e in merged:
        append(text[pos:s])
        n = e - s
        append(stars_cache[n] if n <= limit else stars_cache[limit])
        pos = e
    append(text[pos:])
    return b"".join(parts)


def register_engines() -> dict[str, dict]:
    """
    Each entry is a single mask_fn(patterns, text) -> bytes that does
    EVERYTHING (build/compile + search + reconstruct) in one call, since we're
    only comparing total end-to-end time, matching how each library is
    actually used once on a file.
    """
    engines: dict[str, dict] = {}

    def register(name, mask_fn, available=True, note="", version=None):
        engines[name] = dict(mask=mask_fn, available=available, note=note, version=version)

    import secretsweeper

    def ss_mask(pats: list[bytes], text: bytes) -> bytes:
        return secretsweeper.mask(text, pats, limit=LIMIT)

    register("secretsweeper", ss_mask, version=_lib_version("secretsweeper"))

    import re

    def re_mask(pats: list[bytes], text: bytes) -> bytes:
        pats_sorted = sorted(pats, key=len, reverse=True)
        rx = re.compile(b"|".join(re.escape(p) for p in pats_sorted))

        def repl(m):
            n = m.end() - m.start()
            return b"*" * n if n <= LIMIT else b"*" * LIMIT

        return rx.sub(repl, text)

    register("re (stdlib regex)", re_mask, version=f"python {sys.version.split()[0]}")

    try:
        import ahocorasick

        def pyahc_mask(pats: list[bytes], text: bytes) -> bytes:
            a = ahocorasick.Automaton()
            for p in pats:
                s = p.decode("latin-1")
                a.add_word(s, len(s))
            a.make_automaton()
            text_str = text.decode("latin-1")
            spans = [(end - plen + 1, end + 1) for end, plen in a.iter(text_str)]
            return apply_spans(text, spans)

        register("pyahocorasick", pyahc_mask, version=_lib_version("pyahocorasick"))
    except ImportError as e:
        register("pyahocorasick", None, available=False, note=str(e))

    try:
        import ahocorasick_rs

        def acrs_mask(pats: list[bytes], text: bytes) -> bytes:
            a = ahocorasick_rs.BytesAhoCorasick(list(pats))
            spans = [(s, e) for _idx, s, e in a.find_matches_as_indexes(text)]
            return apply_spans(text, spans)

        register("ahocorasick_rs", acrs_mask, version=_lib_version("ahocorasick-rs"))
    except ImportError as e:
        register("ahocorasick_rs", None, available=False, note=str(e))

    try:
        import acora

        def acora_mask(pats: list[bytes], text: bytes) -> bytes:
            builder = acora.AcoraBuilder()
            for p in pats:
                builder.add(p)
            ac = builder.build()
            spans = [(start, start + len(kw)) for kw, start in ac.finditer(text)]
            return apply_spans(text, spans)

        register("acora", acora_mask, version=_lib_version("acora"))
    except ImportError as e:
        register("acora", None, available=False, note=str(e))

    try:
        import ahocorapy.keywordtree as ahocorapy_kt

        def ahp_mask(pats: list[bytes], text: bytes) -> bytes:
            tree = ahocorapy_kt.KeywordTree(case_insensitive=False)
            for p in pats:
                tree.add(p.decode("latin-1"))
            tree.finalize()
            text_str = text.decode("latin-1")
            spans = [(start, start + len(kw)) for kw, start in tree.search_all(text_str)]
            return apply_spans(text, spans)

        register("ahocorapy (pure python)", ahp_mask, version=_lib_version("ahocorapy"))
    except ImportError as e:
        register("ahocorapy (pure python)", None, available=False, note=str(e))

    # noaho excluded entirely: unmaintained, fails to build on modern CPython/arm64.

    return engines


def run_benchmark(n_rounds: int) -> dict:
    corpus = (DATA_DIR / "corpus.bin").read_bytes()
    with (DATA_DIR / "patterns.pkl").open("rb") as f:
        patterns: list[bytes] = pickle.load(f)
    with (DATA_DIR / "manifest.json").open() as f:
        manifest = json.load(f)

    print(f"Corpus: {len(corpus) / 1024 / 1024:.2f} MiB, {len(patterns)} patterns, {n_rounds} interleaved rounds")

    engines = register_engines()
    available_names = [n for n, cfg in engines.items() if cfg["available"]]

    results = {
        name: {"available": cfg["available"], "note": cfg["note"], "version": cfg["version"], "runs_ms": []}
        for name, cfg in engines.items()
    }
    reference: dict[str, bytes] = {}

    for r in range(n_rounds):
        order = available_names[r % len(available_names) :] + available_names[: r % len(available_names)]
        print(f"\n--- round {r + 1}/{n_rounds} ---")
        for name in order:
            cfg = engines[name]
            t0 = time.perf_counter()
            masked = cfg["mask"](patterns, corpus)
            elapsed = time.perf_counter() - t0
            results[name]["runs_ms"].append(elapsed * 1000)

            if name not in reference:
                reference[name] = masked
                for p in patterns:
                    assert p not in masked, f"{name} leaked a secret: {p[:30]!r}"
            mb_s = len(corpus) / elapsed / 1e6
            print(f"  {name}: {elapsed * 1000:.1f} ms  ({mb_s:.1f} MB/s)")

    ss_ref = reference.get("secretsweeper")
    for name in available_names:
        results[name]["correct"] = (reference[name] == ss_ref) if ss_ref is not None else None
        runs: list[float] = results[name]["runs_ms"]
        min_ms = min(runs)
        avg_ms = sum(runs) / len(runs)
        results[name]["min_ms"] = min_ms
        results[name]["avg_ms"] = avg_ms
        results[name]["min_mb_s"] = len(corpus) / (min_ms / 1000) / 1e6
        results[name]["avg_mb_s"] = len(corpus) / (avg_ms / 1000) / 1e6

    print(f"\n=== Summary ({n_rounds} interleaved rounds) ===")
    for name in available_names:
        res = results[name]
        print(
            f"  {name}: min={res['min_ms']:.1f}ms ({res['min_mb_s']:.1f} MB/s)  "
            f"avg={res['avg_ms']:.1f}ms ({res['avg_mb_s']:.1f} MB/s)  correct={res['correct']}"
        )

    return {
        "corpus_bytes": len(corpus),
        "n_patterns": len(patterns),
        "n_rounds": n_rounds,
        "manifest": manifest,
        "results": results,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--rounds", type=int, default=5, help="interleaved A/B rounds per engine (default: 5)")
    parser.add_argument("--generate", action="store_true", help="regenerate the corpus first")
    args = parser.parse_args()

    if args.generate or not (DATA_DIR / "corpus.bin").exists():
        import gen_corpus

        gen_corpus.main()

    data = run_benchmark(args.rounds)

    out_path = DATA_DIR / "results.json"
    with out_path.open("w") as f:
        json.dump(data, f, indent=2, default=str)
    print(f"\nSaved {out_path}")


if __name__ == "__main__":
    main()
